// Writes src/problems.gen.ts: every practice problem folder's files, so the
// Worker can verify solutions against the same problems the practice page
// shows (the page gets them from Vite's import.meta.glob instead).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** The `## <title>` section of a Markdown file without its heading, up to the next level-2 heading outside a code fence; '' when absent. */
function h2Section(source, title) {
  const out = [];
  let inside = false;
  let fence = false;
  for (const line of source.replace(/\r\n?/g, '\n').split('\n')) {
    if (/^(```|~~~)/.test(line)) fence = !fence;
    if (!fence && /^## /.test(line)) {
      if (inside) break;
      inside = line.slice(3).trim() === title;
      continue;
    }
    if (inside) out.push(line);
  }
  return out.join('\n').trim();
}

const root = new URL('../../frontend/src/practice/problems/', import.meta.url).pathname;
const problems = {};
// The AI interviewer's share of the reader files (src/ai/context.ts): interview.md and the lesson's "In the interview" section.
const interviewFiles = {};
for (const id of readdirSync(root).sort()) {
  const folder = join(root, id);
  if (!statSync(folder).isDirectory()) continue;
  const files = {};
  const read = (dir, prefix) => {
    for (const name of readdirSync(dir).sort()) {
      const path = join(dir, name);
      if (statSync(path).isDirectory()) read(path, `${prefix}${name}/`);
      // The lesson, interview and walkthrough are for readers; the Worker only checks solutions, so they stay out of the bundle.
      else if (!(prefix === '' && ['lesson.md', 'interview.md', 'guided.md'].includes(name))) files[`${prefix}${name}`] = readFileSync(path, 'utf8');
    }
  };
  read(folder, '');
  problems[id] = files;
  const text = (name) => {
    try {
      return readFileSync(join(folder, name), 'utf8');
    } catch {
      return '';
    }
  };
  interviewFiles[id] = { interview: text('interview.md'), lessonInterview: h2Section(text('lesson.md'), 'In the interview') };
}
writeFileSync(
  new URL('../src/problems.gen.ts', import.meta.url),
  `// Generated by scripts/problems.mjs from frontend/src/practice/problems; do not edit.\n` +
    `export const problemFolders: Record<string, Record<string, string>> = ${JSON.stringify(problems, null, 2)};\n`,
);
writeFileSync(
  new URL('../src/ai/interviewFiles.gen.ts', import.meta.url),
  `// Generated by scripts/problems.mjs from frontend/src/practice/problems; do not edit.\n` +
    `export const interviewFiles: Record<string, { interview: string; lessonInterview: string }> = ${JSON.stringify(interviewFiles, null, 2)};\n`,
);
