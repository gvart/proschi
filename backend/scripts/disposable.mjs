#!/usr/bin/env node
// Refreshes src/disposableDomains.ts from the community-maintained blocklist
// at github.com/disposable-email-domains/disposable-email-domains (CC0).
// Accounts on these domains get no free sign-up credits (src/signupCredits.ts).
//
//   node scripts/disposable.mjs              download the current list
//   node scripts/disposable.mjs <file.conf>  use a downloaded copy instead
//
// Commit the result; the Worker bundles it, nothing is fetched at run time.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';
const OUT = fileURLToPath(new URL('../src/disposableDomains.ts', import.meta.url));
// Never on the list, whatever the download says: a bad upstream edit must not refuse everyone.
const NEVER = new Set([
  'gmail.com', 'googlemail.com', 'outlook.com', 'hotmail.com', 'live.com', 'yahoo.com', 'icloud.com', 'me.com', 'proton.me', 'protonmail.com',
  'gmx.de', 'gmx.net', 'web.de', 'aol.com', 'yandex.ru', 'mail.ru', 'fastmail.com', 'hey.com', 'zoho.com', 'tutanota.com', 'qq.com', '163.com',
]);

const file = process.argv[2];
const text = file
  ? readFileSync(file, 'utf8')
  : await fetch(SOURCE).then((r) => {
      if (!r.ok) throw new Error(`${SOURCE}: ${r.status}`);
      return r.text();
    });
const domains = [
  ...new Set(
    text
      .split('\n')
      .map((l) => l.trim().toLowerCase())
      .filter((l) => l && !l.startsWith('#') && /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(l) && !NEVER.has(l)),
  ),
].sort();
if (domains.length < 1000) throw new Error(`Only ${domains.length} domains: refusing to replace the list`);

writeFileSync(
  OUT,
  '// Generated by scripts/disposable.mjs from github.com/disposable-email-domains/disposable-email-domains (CC0).\n' +
    `// Do not edit: run \`node scripts/disposable.mjs\` to refresh. ${domains.length} domains, one per line.\n` +
    `export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join('\n'))};\n`,
);
console.log(`Wrote ${domains.length} domains to src/disposableDomains.ts`);
