// Writes src/dsl/stdlib/sources.gen.ts from the .proschi files next to it, so
// the stdlib is plain TypeScript to every bundler (Vite here, esbuild in
// tooling/). src/dsl/typesys/stdlib.test.ts fails when it is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../src/dsl/stdlib/', import.meta.url));

// core.proschi first (it declares the root types), then by name.
const names = readdirSync(dir)
  .filter((n) => n.endsWith('.proschi'))
  .sort((a, b) => (a === 'core.proschi' ? -1 : b === 'core.proschi' ? 1 : a.localeCompare(b)));

const entries = names.map((name) => `  { path: ${JSON.stringify(`stdlib/${name}`)}, source: ${JSON.stringify(readFileSync(dir + name, 'utf8'))} },`);
writeFileSync(
  dir + 'sources.gen.ts',
  [
    '// Generated by scripts/gen-stdlib.mjs from src/dsl/stdlib/*.proschi; run `npm run gen:stdlib` after editing them.',
    '/** The bundled stdlib files, in the order they are read (core.proschi first, then by name). */',
    'export const STDLIB_SOURCES: readonly { path: string; source: string }[] = [',
    ...entries,
    '];',
    '',
  ].join('\n'),
);
