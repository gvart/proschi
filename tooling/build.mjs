// Bundles the CLI and language server (with the parser from frontend/src/dsl
// inlined), the VS Code extension, and regenerates the JSON Schema.
import { build } from 'esbuild';
import { chmodSync, copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync('package.json', 'utf8'));

const common = {
  bundle: true,
  platform: 'node',
  target: 'node18',
  format: 'cjs',
  logLevel: 'warning',
  jsx: 'automatic',
  define: { PROSCHI_VERSION: JSON.stringify(version) },
};

// The renderer pulls in frontend files that import these packages; take them from
// tooling/node_modules (one copy of React, and no need for frontend/node_modules).
const RENDER_PACKAGES = ['elkjs', 'react', 'react-dom', 'react-icons', 'lucide-react'];
const renderAlias = Object.fromEntries(RENDER_PACKAGES.map((p) => [p, `./node_modules/${p}`]));

// `proschi render` lives in dist/render.cjs, which cli.cjs loads only for that
// command, so check, parse, fmt and the language server stay small.
const externalRenderer = {
  name: 'external-renderer',
  setup(b) {
    b.onResolve({ filter: /^\.\/render\/command$/ }, () => ({ path: './render.cjs', external: true }));
  },
};
// share-link encodes with lz-string, which frontend/src/playground/share.ts imports.
await build({ ...common, entryPoints: ['src/cli.ts'], outfile: 'dist/cli.cjs', banner: { js: '#!/usr/bin/env node' }, plugins: [externalRenderer], alias: { 'lz-string': './node_modules/lz-string' } });
await build({ ...common, entryPoints: ['src/render/command.ts'], outfile: 'dist/render.cjs', alias: renderAlias, minify: true });
await build({ ...common, entryPoints: ['src/server.ts'], outfile: 'dist/server.cjs', banner: { js: '#!/usr/bin/env node' } });
chmodSync('dist/cli.cjs', 0o755);
chmodSync('dist/server.cjs', 0o755);

// The schema module only needs the catalog; bundle it to a temp file and run it.
await build({ ...common, entryPoints: ['src/schema.ts'], outfile: 'dist/.schema.cjs' });
const { createRequire } = await import('node:module');
const { diagramSchema } = createRequire(import.meta.url)('./dist/.schema.cjs');
mkdirSync('schema', { recursive: true });
writeFileSync('schema/proschi-diagram.schema.json', JSON.stringify(diagramSchema(), null, 2) + '\n');
rmSync('dist/.schema.cjs');

// The canvas's icon names per tech stack and component type, for the terminal renderer's glyphs.
await build({ ...common, entryPoints: ['scripts/techIconNames.tsx'], outfile: 'dist/.icons.cjs', alias: renderAlias });
const { execFileSync } = await import('node:child_process');
const iconNames = execFileSync(process.execPath, ['dist/.icons.cjs'], { encoding: 'utf8' });
rmSync('dist/.icons.cjs');
writeFileSync(
  'src/terminal/techIcons.gen.ts',
  `// Generated by build.mjs from frontend/src/utils/iconMapping.tsx: the icon the canvas draws per tech stack and component type.\n` +
    `export const ICON_NAMES: { tech: Record<string, string>; type: Record<string, string> } = ${iconNames};\n`,
);

// Claude Code plugin (../plugin): the hooks module that draws diagrams in the terminal, an ES
// module with no Node or DOM, kept under the engine's 1 MiB per file, so without ELK; and the
// layout helper the hooks run in Node, which carries ELK.
await build({
  ...common,
  entryPoints: ['../plugin/src/register.tsx'],
  outfile: '../plugin/hooks/register.js',
  platform: 'neutral',
  format: 'esm',
  mainFields: ['module', 'main'],
  jsx: 'transform',
  jsxFactory: 'h',
  jsxFragment: 'Fragment',
  external: ['claude-code', 'elkjs', 'elkjs/*'],
  alias: { 'lz-string': './node_modules/lz-string' },
  // Not minified: the engine reads the module's source, where `register`, `on` and `$` keep their names and shape.
  legalComments: 'none',
});
const hooks = readFileSync('../plugin/hooks/register.js', 'utf8');
if (hooks.includes('import(') || hooks.includes('elkjs')) throw new Error('plugin/hooks/register.js must not load ELK or use import()');
if (hooks.length > 1024 * 1024) throw new Error(`plugin/hooks/register.js is ${hooks.length} bytes, over the 1 MiB a hooks module may be`);
await build({ ...common, entryPoints: ['src/terminal/layoutHost.ts'], outfile: '../plugin/hooks/layout.cjs', alias: { ...renderAlias, 'lz-string': './node_modules/lz-string' }, minify: true, legalComments: 'none' });

// VS Code extension: its own client bundle (minified, as the preview carries the renderer),
// plus copies of the server and grammar.
await build({ ...common, entryPoints: ['vscode/src/extension.ts'], outfile: 'vscode/dist/extension.cjs', external: ['vscode'], alias: renderAlias, minify: true });
copyFileSync('dist/server.cjs', 'vscode/dist/server.cjs');
// Both packages ship the repository's license.
copyFileSync('../LICENSE', 'LICENSE');
copyFileSync('../LICENSE', 'vscode/LICENSE');
mkdirSync('vscode/syntaxes', { recursive: true });
copyFileSync('grammar/proschi.tmLanguage.json', 'vscode/syntaxes/proschi.tmLanguage.json');
